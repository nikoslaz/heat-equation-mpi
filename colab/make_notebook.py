"""Generate colab/heat_cuda.ipynb: a Google Colab notebook that contains the project's source
files, builds them with CMake, runs the CUDA tests and benchmarks, and plots the result.

Run it again after changing the code:  python3 colab/make_notebook.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = [
    "CMakeLists.txt",
    "src/mpi/main.cpp", "src/mpi/heat_mpi.hpp", "src/mpi/heat_mpi.cpp",
    "src/cuda/cuda_check.hpp", "src/cuda/heat_gpu.hpp", "src/cuda/heat_gpu.cu", "src/cuda/heat_reference.hpp",
    "src/cuda/heat_cuda.cpp", "src/cuda/heat_mpi_cuda.cpp",
    "scripts/test_cuda.sh", "scripts/bench_cuda.sh",
]


def lines(text):
    """Notebook cell source: a list of lines, each ending in a newline except the last."""
    parts = text.strip("\n").split("\n")
    return [p + "\n" for p in parts[:-1]] + [parts[-1]]


def markdown(text):
    return {"cell_type": "markdown", "metadata": {}, "source": lines(text)}


def code(text):
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": lines(text)}


sources = {name: (ROOT / name).read_text() for name in FILES}
write_files = "\n".join(
    ["# Project files (generated by colab/make_notebook.py from the repository)", "import os", "", "FILES = {"]
    + [f"    {name!r}: {content!r}," for name, content in sources.items()]
    + [
        "}",
        "",
        'os.makedirs("/content/heat", exist_ok=True)',
        'os.chdir("/content/heat")',
        'os.makedirs("results", exist_ok=True)',
        "for name, content in FILES.items():",
        "    os.makedirs(os.path.dirname(name) or '.', exist_ok=True)",
        "    with open(name, 'w') as f:",
        "        f.write(content)",
        "    if name.endswith('.sh'):",
        "        os.chmod(name, 0o755)",
        'print("Wrote", len(FILES), "files to", os.getcwd())',
    ]
)

cells = [
    markdown("""
# 2D heat equation on the GPU (CUDA)

1. **Runtime → Change runtime type → T4 GPU** (any NVIDIA GPU works).
2. **Runtime → Run all**.

The notebook writes the project files, builds them with CMake, checks every CUDA kernel against a CPU run,
benchmarks them, and plots the temperature. The tables are saved to `results/results_cuda.md`.
"""),
    code(write_files),
    markdown("## Tools: GPU, CUDA, CMake, MPI"),
    code("""
import os, shutil
# Colab runs as root; Open MPI refuses that unless told it is fine.
os.environ["OMPI_ALLOW_RUN_AS_ROOT"] = "1"
os.environ["OMPI_ALLOW_RUN_AS_ROOT_CONFIRM"] = "1"
if shutil.which("mpicxx") is None:
    !apt-get -qq update > /dev/null && apt-get -qq install -y openmpi-bin libopenmpi-dev > /dev/null
!nvidia-smi --query-gpu=name,compute_cap,memory.total --format=csv
!nvcc --version | tail -2
!cmake --version | head -1
!mpirun --version | head -1
"""),
    markdown("## Build"),
    code("""
cap = !nvidia-smi --query-gpu=compute_cap --format=csv,noheader
arch = cap[0].strip().replace(".", "")   # e.g. 7.5 -> 75 for a T4
!cmake -S . -B build -DCMAKE_BUILD_TYPE=Release -DCMAKE_CUDA_ARCHITECTURES={arch} 2>&1 | tail -3
!cmake --build build -j 4 2>&1 | grep -E "error|warning|Built target"
"""),
    markdown("## Correctness\nEvery kernel, in double and float, is compared point by point with a CPU run."),
    code("!./scripts/test_cuda.sh"),
    markdown("## Benchmark\nTakes a minute or two."),
    code("!./scripts/bench_cuda.sh > /dev/null && cat results/results_cuda.md"),
    markdown("## Plot"),
    code("""
!./build/heat_cuda 1000 256 --kernel temporal
import numpy as np
import matplotlib.pyplot as plt
grid = np.loadtxt("grid.csv", delimiter=",")
plt.imshow(grid, cmap="hot")
plt.colorbar(label="temperature")
plt.title("2D heat equation on the GPU (top edge = 100)")
plt.show()
"""),
    markdown("## Download the results (optional)"),
    code("""
from google.colab import files
files.download("results/results_cuda.md")
"""),
]

notebook = {
    "nbformat": 4,
    "nbformat_minor": 0,
    "metadata": {
        "accelerator": "GPU",
        "colab": {"provenance": [], "gpuType": "T4"},
        "kernelspec": {"name": "python3", "display_name": "Python 3"},
        "language_info": {"name": "python"},
    },
    "cells": cells,
}

out = ROOT / "colab" / "heat_cuda.ipynb"
out.write_text(json.dumps(notebook, indent=1) + "\n")
print("Wrote", out.relative_to(ROOT))
